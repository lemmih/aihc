{-# LANGUAGE OverloadedStrings #-}

-- |
-- Module      : Aihc.Haddock.Hoogle
-- Description : Render the documentation model as a Hoogle text database
--
-- Follows the layout of Haddock's Hoogle backend: a header with the package
-- name and version, then for each exposed module its documentation, the
-- @module@ line, the exported declarations with their documentation rendered
-- as simple HTML, and the module's instances.
module Aihc.Haddock.Hoogle
  ( renderHoogle,
    renderHoogleModule,
  )
where

import Aihc.Haddock.Markup (parseInline)
import Aihc.Haddock.Model
import Data.List (sortOn)
import Data.Maybe (fromMaybe, mapMaybe)
import Data.Text (Text)
import Data.Text qualified as T

renderHoogle :: PackageDoc -> Text
renderHoogle package =
  T.unlines $
    [ "-- Hoogle documentation, generated by Haddock",
      "-- See Hoogle, http://www.haskell.org/hoogle/",
      "",
      "@package " <> packageDocName package,
      "@version " <> packageDocVersion package,
      ""
    ]
      <> concatMap renderHoogleModule (filter moduleDocExposed (packageDocModules package))

renderHoogleModule :: ModuleDoc -> [Text]
renderHoogleModule modu =
  [""]
    <> docLines (moduleDocDescription modu)
    <> ["module " <> moduleDocName modu]
    <> concatMap renderEntry (exportedDecls modu)
    <> map renderInstance (sortOn (\i -> (instanceClass i, instanceHead i)) (moduleDocInstances modu))

-- | The declarations Hoogle lists: the exported ones in export order with
-- the subordinates the export list names.
exportedDecls :: ModuleDoc -> [(DeclDoc, [DeclDoc])]
exportedDecls modu =
  case moduleDocExports modu of
    Nothing -> [(decl, flattenSubordinates (declSubordinates decl)) | decl <- moduleDocDecls modu]
    Just items -> mapMaybe exportedItem items
  where
    exportedItem item =
      case item of
        ExportDeclItem name ns subs -> do
          decl <- lookupDecl name ns
          let subordinates =
                case subs of
                  ExportNoSubordinates -> []
                  ExportAllSubordinates -> flattenSubordinates (declSubordinates decl)
                  ExportSomeSubordinates names -> filter ((`elem` names) . declName) (flattenSubordinates (declSubordinates decl))
          pure (decl, subordinates)
        _ -> Nothing
    lookupDecl name ns =
      case [decl | decl <- moduleDocDecls modu, declName decl == name, declNamespace decl == ns] of
        decl : _ -> Just decl
        [] -> Nothing

flattenSubordinates :: [DeclDoc] -> [DeclDoc]
flattenSubordinates = concatMap (\sub -> sub : flattenSubordinates (declSubordinates sub))

renderEntry :: (DeclDoc, [DeclDoc]) -> [Text]
renderEntry (decl, subordinates) =
  renderDecl Nothing decl <> concatMap (renderDecl (Just decl)) subordinates

renderDecl :: Maybe DeclDoc -> DeclDoc -> [Text]
renderDecl parent decl =
  case declLines of
    [] -> []
    _ -> docLines (declDoc decl) <> warningLines <> declLines <> fixityLines
  where
    name = declName decl
    binder = if isOperator name then "(" <> name <> ")" else name
    declLines =
      case declKind decl of
        DeclKindFunction -> signature binder
        DeclKindForeignImport -> signature binder
        DeclKindPatternSynonym -> signature ("pattern " <> binder)
        DeclKindData -> ["data " <> fromMaybe name (declSignature decl)]
        DeclKindNewtype -> ["newtype " <> fromMaybe name (declSignature decl)]
        DeclKindTypeSynonym -> ["type " <> fromMaybe name (declSignature decl)]
        DeclKindClass -> ["class " <> fromMaybe name (declSignature decl)]
        DeclKindTypeFamily -> ["type family " <> fromMaybe name (declSignature decl)]
        DeclKindDataFamily -> ["data family " <> fromMaybe name (declSignature decl)]
        DeclKindAssociatedType -> ["type " <> fromMaybe name (declSignature decl)]
        DeclKindConstructor -> signature binder
        DeclKindField -> signature ("[" <> name <> "]")
        DeclKindMethod -> maybe [] (\sig -> [binder <> " :: " <> methodSignature sig]) (declSignature decl)
    signature prefix = maybe [] (\sig -> [prefix <> " :: " <> sig]) (declSignature decl)
    methodSignature sig =
      case parent >>= classConstraint of
        Nothing -> sig
        Just constraint ->
          case T.breakOn " => " sig of
            (ctx, rest) | not (T.null rest) -> "(" <> constraint <> ", " <> stripParens ctx <> ")" <> rest
            _ -> constraint <> " => " <> sig
    stripParens text = fromMaybe text (T.stripPrefix "(" text >>= T.stripSuffix ")")
    -- Haddock's Hoogle backend renders a DEPRECATED or WARNING pragma as a
    -- second documentation block in italics.
    warningLines =
      case declWarning decl of
        Nothing -> []
        Just message ->
          docLines (Just (plainMetaDoc (DocParagraph (DocEmphasis (DocAppend (DocString "Deprecated: ") (parseInline message))))))
    fixityLines =
      case declFixity decl of
        Nothing -> []
        Just fixity -> [renderFixity fixity <> " " <> name]

-- | The constraint a class puts on its methods: the head of the class
-- signature without the superclass context.
classConstraint :: DeclDoc -> Maybe Text
classConstraint classDecl = do
  sig <- declSignature classDecl
  let (_, rest) = T.breakOn " => " sig
  pure (if T.null rest then sig else T.drop 4 rest)

renderFixity :: Fixity -> Text
renderFixity fixity =
  direction <> " " <> T.pack (show (fixityPrecedence fixity))
  where
    direction =
      case fixityDirection fixity of
        FixityInfix -> "infix"
        FixityInfixL -> "infixl"
        FixityInfixR -> "infixr"

renderInstance :: InstanceDoc -> Text
renderInstance instance' = "instance " <> instanceHead instance'

isOperator :: Text -> Bool
isOperator name =
  case T.uncons name of
    Just (c, _) -> not (c == '_' || c == '\'' || isIdentStart c)
    Nothing -> False
  where
    isIdentStart c = c `elem` (['a' .. 'z'] <> ['A' .. 'Z']) || c > '\x7f'

-- Documentation --------------------------------------------------------------

-- | Documentation as Hoogle comment lines, preceded by a blank line.
docLines :: Maybe MetaDoc -> [Text]
docLines mdoc =
  case mdoc of
    Nothing -> []
    Just meta ->
      case blockLines (metaDoc meta) of
        [] -> []
        first : rest -> "" : ("-- | " <> first) : map ("--   " <>) rest

-- | Render a document as lines, blocks separated by blank lines.
blockLines :: Doc -> [Text]
blockLines doc =
  joinBlocks (map blockToLines (blocks doc))
  where
    joinBlocks [] = []
    joinBlocks [single] = single
    joinBlocks (block : rest) = block <> [""] <> joinBlocks rest

blocks :: Doc -> [Doc]
blocks doc =
  case doc of
    DocEmpty -> []
    DocAppend a b -> blocks a <> blocks b
    _ -> [doc]

blockToLines :: Doc -> [Text]
blockToLines doc =
  case doc of
    DocParagraph inner -> wrapLines 70 (inlineText inner)
    DocCodeBlock inner -> ["<pre>"] <> T.lines (escape (plainText inner)) <> ["</pre>"]
    DocExamples examples ->
      ["<pre>"] <> concat [("&gt;&gt;&gt; " <> escape (exampleExpression e)) : map escape (exampleResult e) | e <- examples] <> ["</pre>"]
    DocProperty prop -> ["<pre>", escape prop, "</pre>"]
    DocHeader level title ->
      let tag = "h" <> T.pack (show level)
       in ["<" <> tag <> ">" <> inlineText title <> "</" <> tag <> ">"]
    DocUnorderedList items -> ["<ul>"] <> map (\item -> "<li>" <> itemText item <> "</li>") items <> ["</ul>"]
    DocOrderedList items -> ["<ol>"] <> map (\(_, item) -> "<li>" <> itemText item <> "</li>") items <> ["</ol>"]
    DocDefList items -> ["<ul>"] <> map (\(term, def) -> "<li><i>" <> inlineText term <> "</i> " <> inlineText def <> "</li>") items <> ["</ul>"]
    DocTable _ -> ["TODO: table"]
    DocWarning inner -> blockLines inner
    _ -> wrapLines 70 (inlineText doc)
  where
    itemText item =
      case item of
        DocParagraph inner -> inlineText inner
        _ -> inlineText item

inlineText :: Doc -> Text
inlineText doc =
  case doc of
    DocEmpty -> ""
    DocAppend a b -> inlineText a <> inlineText b
    DocString text -> escape text
    DocParagraph inner -> inlineText inner
    DocIdentifier name -> "<a>" <> escape name <> "</a>"
    DocIdentifierUnchecked _ name -> "<a>" <> escape name <> "</a>"
    DocModule name -> "<a>" <> escape name <> "</a>"
    DocWarning inner -> inlineText inner
    DocEmphasis inner -> "<i>" <> inlineText inner <> "</i>"
    DocMonospaced inner -> "<tt>" <> inlineText inner <> "</tt>"
    DocBold inner -> "<b>" <> inlineText inner <> "</b>"
    DocHyperlink url label -> "<a>" <> maybe (escape url) inlineText label <> "</a>"
    DocPic _ _ -> ""
    DocMathInline _ -> "&lt;math&gt;"
    DocMathDisplay _ -> "&lt;math&gt;"
    DocAName _ -> ""
    DocCodeBlock inner -> "<pre>" <> inlineText inner <> "</pre>"
    _ -> T.unwords (blockToLines doc)

plainText :: Doc -> Text
plainText doc =
  case doc of
    DocEmpty -> ""
    DocAppend a b -> plainText a <> plainText b
    DocString text -> text
    DocIdentifier name -> name
    DocIdentifierUnchecked modName name -> modName <> "." <> name
    DocModule name -> name
    DocParagraph inner -> plainText inner
    DocEmphasis inner -> plainText inner
    DocMonospaced inner -> plainText inner
    DocBold inner -> plainText inner
    DocWarning inner -> plainText inner
    DocCodeBlock inner -> plainText inner
    DocHyperlink url label -> maybe url plainText label
    _ -> ""

escape :: Text -> Text
escape = T.concatMap escapeChar
  where
    escapeChar c =
      case c of
        '&' -> "&amp;"
        '<' -> "&lt;"
        '>' -> "&gt;"
        _ -> T.singleton c

-- | Greedy word wrap that keeps the paragraph's own line breaks out of the
-- picture: the text is re-flowed.
wrapLines :: Int -> Text -> [Text]
wrapLines width text =
  case T.words text of
    [] -> []
    firstWord : rest -> go firstWord rest
  where
    go current [] = [current]
    go current (word : rest)
      | T.length current + 1 + T.length word > width = current : go word rest
      | otherwise = go (current <> " " <> word) rest
